"""CSV output helpers."""
from pathlib import Path
import pandas as pd


def write_table(frame: pd.DataFrame, path: Path, index: bool = False) -> None:
    """Create parent folders and write one UTF-8 CSV."""
    path.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(path, index=index)


def write_run_report(path: Path, source_label: str, quality: dict[str, object], sessions: int,
                     train_sessions: int, test_sessions: int, journeys: int, seed: int,
                     threshold_minutes: int, metrics: pd.DataFrame, probabilities: pd.DataFrame) -> None:
    """Write a compact, explicitly labelled summary from this run's results."""
    path.parent.mkdir(parents=True, exist_ok=True)
    report = f"""# Run summary

**Data label:** {source_label}

## Data and setup

- CSV rows read into this run: {quality.get('rows_read', 'not available')}
- Rows retained after cleaning: {quality.get('rows_retained', 'not available')}
- Rows excluded: {quality.get('rows_excluded', 'not available')}
- Sessions used: {sessions} (training: {train_sessions}; held out: {test_sessions})
- Inactivity threshold: {threshold_minutes} minutes
- Simulated journeys: {journeys}; random seed: {seed}

## Training transition probability matrix

```text
{probabilities.to_string(float_format=lambda value: f'{value:.4f}')}
```

## Held-out observed versus simulated outcomes

```text
{metrics.to_string(index=False, float_format=lambda value: f'{value:.4f}')}
```

Simulation output describes paths generated by the fitted model. These comparisons do not establish real-world predictive accuracy.
"""
    path.write_text(report, encoding="utf-8")
